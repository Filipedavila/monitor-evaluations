import { Evaluation } from '@domains/evaluation/domain/entities/evaluation.entity';
import {
  ArtifactType,
  EvaluationArtifact,
} from '@domains/evaluation/domain/entities/evaluation-artifacts.entity';
import { EvaluationContext } from '@domains/evaluation/domain/entities/contexts-evaluation.entity';
import { Page } from '@domains/inventory/page/page.entity';
import { User } from '@domains/identity/user/user.entity';
import { Context } from '@domains/inventory/context/context.identity';
import { DataSource, QueryFailedError } from 'typeorm';
import { startTestDatabase, TestDatabase } from 'test/helpers/postgres-test-db';
import { expectPgError, PgErrorCode, pgErrorCodeOf } from 'test/helpers/pg-errors';
import {
  createArtifact,
  createContext,
  createEvaluation,
  createPage,
  createUser,
  insertArtifact,
  linkEvaluationToContext,
} from '@factories/evaluation.factory';

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

describe('Evaluation entities (PostgreSQL integration)', () => {
  let db: TestDatabase;
  let ds: DataSource;

  beforeAll(async () => {
    db = await startTestDatabase();
    ds = db.dataSource;
  });

  afterAll(async () => {
    await db.stop();
  });

  beforeEach(async () => {
    await db.truncateAll();
  });

  describe('Evaluation', () => {
    it('persists a minimal evaluation and applies database defaults', async () => {
      const page = await createPage(ds);
      const saved = await createEvaluation(ds, { pageId: page.id });

      const found = await ds.getRepository(Evaluation).findOneByOrFail({ id: saved.id });

      expect(found.pageId).toBe(page.id);
      expect(found.pageTitle).toBeNull();
      expect(found.score).toBeNull();
      expect(found.A).toBeNull();
      expect(found.AA).toBeNull();
      expect(found.AAA).toBeNull();
      expect(found.tagCount).toBeNull();
      expect(found.frozenAt).toBeNull();
      expect(found.createdById).toBeNull();
      expect(found.updatedById).toBeNull();
      expect(found.createdAt).toBeInstanceOf(Date);
      expect(found.updatedAt).toBeInstanceOf(Date);
      expect(found.isFrozen).toBe(false);
    });

    it('generates sequential identity ids starting at 1 after a reset', async () => {
      const page = await createPage(ds);

      const first = await createEvaluation(ds, { pageId: page.id });
      const second = await createEvaluation(ds, { pageId: page.id });

      expect(first.id).toBe(1);
      expect(second.id).toBe(2);
    });

    it('accepts an explicit id (identity GENERATED BY DEFAULT)', async () => {
      const page = await createPage(ds);

      await ds.getRepository(Evaluation).insert({
        id: 9000,
        pageId: page.id,
        evaluationDate: new Date('2024-01-01T00:00:00.000Z'),
      });

      await expect(ds.getRepository(Evaluation).existsBy({ id: 9000 })).resolves.toBe(true);
    });

    it('preserves the exact instant of evaluationDate (timestamptz)', async () => {
      const evaluationDate = new Date('2024-03-15T10:30:45.123Z');
      const saved = await createEvaluation(ds, { evaluationDate });

      const found = await ds.getRepository(Evaluation).findOneByOrFail({ id: saved.id });

      expect(found.evaluationDate.getTime()).toBe(evaluationDate.getTime());
    });

    it('stores conformance counters and tag count', async () => {
      const saved = await createEvaluation(ds, { A: 3, AA: 2, AAA: 0, tagCount: 1500 });

      const found = await ds.getRepository(Evaluation).findOneByOrFail({ id: saved.id });

      expect(found).toMatchObject({ A: 3, AA: 2, AAA: 0, tagCount: 1500 });
    });

    describe('score decimal(4,1)', () => {
      it.each([
        ['87.5', '87.5'],
        ['100', '100.0'],
        ['0', '0.0'],
        ['999.9', '999.9'],
        ['87.46', '87.5'],
        ['99.95', '100.0'],
      ])('stores %s as %s', async (input, expected) => {
        const saved = await createEvaluation(ds, { score: input });

        const found = await ds.getRepository(Evaluation).findOneByOrFail({ id: saved.id });

        expect(found.score).toBe(expected);
      });

      it.each(['1000', '10000.5', '-1000'])('rejects %s (numeric overflow)', async (score) => {
        const page = await createPage(ds);

        await expectPgError(
          () =>
            ds.getRepository(Evaluation).insert({
              pageId: page.id,
              evaluationDate: new Date(),
              score,
            }),
          PgErrorCode.NUMERIC_OUT_OF_RANGE,
        );
      });
    });

    describe('page_title varchar(255)', () => {
      it('accepts exactly 255 characters', async () => {
        const pageTitle = 'a'.repeat(255);
        const saved = await createEvaluation(ds, { pageTitle });

        const found = await ds.getRepository(Evaluation).findOneByOrFail({ id: saved.id });

        expect(found.pageTitle).toHaveLength(255);
      });

      it('rejects 256 characters', async () => {
        const page = await createPage(ds);

        await expectPgError(
          () =>
            ds.getRepository(Evaluation).insert({
              pageId: page.id,
              evaluationDate: new Date(),
              pageTitle: 'a'.repeat(256),
            }),
          PgErrorCode.STRING_TOO_LONG,
        );
      });

      it('preserves unicode characters', async () => {
        const pageTitle = 'Avaliação – página inicial ✓';
        const saved = await createEvaluation(ds, { pageTitle });

        const found = await ds.getRepository(Evaluation).findOneByOrFail({ id: saved.id });

        expect(found.pageTitle).toBe(pageTitle);
      });
    });

    describe('constraints', () => {
      it('rejects an evaluation without pageId (NOT NULL)', async () => {
        await expectPgError(
          () => ds.getRepository(Evaluation).insert({ evaluationDate: new Date() }),
          PgErrorCode.NOT_NULL_VIOLATION,
        );
      });

      it('rejects a pageId that does not exist (FK)', async () => {
        await expectPgError(
          () =>
            ds.getRepository(Evaluation).insert({ pageId: 999_999, evaluationDate: new Date() }),
          PgErrorCode.FOREIGN_KEY_VIOLATION,
        );
      });

      it('rejects a createdById that does not exist (FK)', async () => {
        const page = await createPage(ds);

        await expectPgError(
          () =>
            ds.getRepository(Evaluation).insert({
              pageId: page.id,
              evaluationDate: new Date(),
              createdById: 999_999,
            }),
          PgErrorCode.FOREIGN_KEY_VIOLATION,
        );
      });

      it('rejects an updatedById that does not exist (FK)', async () => {
        const page = await createPage(ds);

        await expectPgError(
          () =>
            ds.getRepository(Evaluation).insert({
              pageId: page.id,
              evaluationDate: new Date(),
              updatedById: 999_999,
            }),
          PgErrorCode.FOREIGN_KEY_VIOLATION,
        );
      });

      it('blocks deleting a user that is referenced as creator (no cascade)', async () => {
        const user = await createUser(ds);
        await createEvaluation(ds, { createdById: user.id });

        await expectPgError(
          () => ds.getRepository(User).delete(user.id),
          PgErrorCode.FOREIGN_KEY_VIOLATION,
        );
      });

      it('allows deleting a user once no evaluation references it', async () => {
        const user = await createUser(ds);

        await ds.getRepository(User).delete(user.id);

        await expect(ds.getRepository(User).count()).resolves.toBe(0);
      });
    });

    describe('relations', () => {
      it('loads page, createdBy and updatedBy', async () => {
        const page = await createPage(ds, { url: 'https://example.com/relations' });
        const creator = await createUser(ds, { username: 'creator' });
        const updater = await createUser(ds, { username: 'updater' });
        const saved = await createEvaluation(ds, {
          pageId: page.id,
          createdById: creator.id,
          updatedById: updater.id,
        });

        const found = await ds.getRepository(Evaluation).findOneOrFail({
          where: { id: saved.id },
          relations: { page: true, createdBy: true, updatedBy: true },
        });

        expect(found.page.url).toBe('https://example.com/relations');
        expect(found.createdBy.username).toBe('creator');
        expect(found.updatedBy?.username).toBe('updater');
      });

      it('returns null for updatedBy when it is not set', async () => {
        const saved = await createEvaluation(ds);

        const found = await ds.getRepository(Evaluation).findOneOrFail({
          where: { id: saved.id },
          relations: { updatedBy: true },
        });

        expect(found.updatedBy).toBeNull();
      });
    });

    describe('freezing', () => {
      it('round-trips frozenAt and toggles isFrozen', async () => {
        const repository = ds.getRepository(Evaluation);
        const saved = await createEvaluation(ds);
        const frozenAt = new Date('2024-06-01T12:00:00.000Z');

        await repository.update(saved.id, { frozenAt });
        const frozen = await repository.findOneByOrFail({ id: saved.id });
        expect(frozen.frozenAt?.getTime()).toBe(frozenAt.getTime());
        expect(frozen.isFrozen).toBe(true);

        await repository.update(saved.id, { frozenAt: null });
        const unfrozen = await repository.findOneByOrFail({ id: saved.id });
        expect(unfrozen.frozenAt).toBeNull();
        expect(unfrozen.isFrozen).toBe(false);
      });
    });

    describe('timestamps', () => {
      it('refreshes updatedAt on update and keeps createdAt untouched', async () => {
        const repository = ds.getRepository(Evaluation);
        const saved = await createEvaluation(ds, { score: '50.0' });
        const before = await repository.findOneByOrFail({ id: saved.id });

        await sleep(25);
        await repository.update(saved.id, { score: '60.0' });
        const after = await repository.findOneByOrFail({ id: saved.id });

        expect(after.updatedAt.getTime()).toBeGreaterThan(before.updatedAt.getTime());
        expect(after.createdAt.getTime()).toBe(before.createdAt.getTime());
      });
    });

    describe('indexes', () => {
      it('creates the composite index on (page_id, created_at)', async () => {
        const rows = await ds.query<Array<{ indexdef: string }>>(
          `SELECT indexdef FROM pg_indexes
           WHERE tablename = 'evaluations' AND indexname = 'idx_evaluations_page_created'`,
        );

        expect(rows).toHaveLength(1);
        expect(rows[0].indexdef).toContain('(page_id, created_at)');
      });

      it('creates an index on created_by_id', async () => {
        const rows = await ds.query<Array<{ indexdef: string }>>(
          `SELECT indexdef FROM pg_indexes WHERE tablename = 'evaluations'`,
        );

        expect(rows.some((row) => row.indexdef.includes('(created_by_id)'))).toBe(true);
      });
    });

    describe('concurrency', () => {
      it('assigns unique ids to evaluations created in parallel', async () => {
        const page = await createPage(ds);

        const created = await Promise.all(
          Array.from({ length: 25 }, () => createEvaluation(ds, { pageId: page.id })),
        );

        expect(new Set(created.map((evaluation) => evaluation.id)).size).toBe(25);
        await expect(ds.getRepository(Evaluation).countBy({ pageId: page.id })).resolves.toBe(25);
      });

      it('applies parallel updates to different rows without interference', async () => {
        const repository = ds.getRepository(Evaluation);
        const page = await createPage(ds);
        const created = await Promise.all(
          Array.from({ length: 10 }, () => createEvaluation(ds, { pageId: page.id })),
        );

        const evaluations = [...created].sort((a, b) => a.id - b.id);

        await Promise.all(
          evaluations.map((evaluation, index) =>
            repository.update(evaluation.id, { tagCount: index * 10 }),
          ),
        );

        const reloaded = await repository.find({
          where: { pageId: page.id },
          order: { id: 'ASC' },
        });

        expect(reloaded.map((evaluation) => evaluation.tagCount)).toEqual(
          evaluations.map((_, index) => index * 10),
        );
      });
    });
  });

  describe('Cascading deletes', () => {
    it('removes evaluations, artifacts and context links when the page is deleted', async () => {
      const page = await createPage(ds);
      const context = await createContext(ds);
      const evaluation = await createEvaluation(ds, { pageId: page.id });
      await createArtifact(ds, evaluation.id);
      await linkEvaluationToContext(ds, evaluation.id, context.id);

      await ds.getRepository(Page).delete(page.id);

      await expect(ds.getRepository(Evaluation).count()).resolves.toBe(0);
      await expect(ds.getRepository(EvaluationArtifact).count()).resolves.toBe(0);
      await expect(ds.getRepository(EvaluationContext).count()).resolves.toBe(0);
      await expect(ds.getRepository(Context).count()).resolves.toBe(1);
    });

    it('does not touch evaluations from other pages', async () => {
      const keptPage = await createPage(ds);
      const removedPage = await createPage(ds);
      await createEvaluation(ds, { pageId: keptPage.id });
      await createEvaluation(ds, { pageId: removedPage.id });

      await ds.getRepository(Page).delete(removedPage.id);

      const remaining = await ds.getRepository(Evaluation).find();
      expect(remaining).toHaveLength(1);
      expect(remaining[0].pageId).toBe(keptPage.id);
    });
  });

  describe('Transactions', () => {
    it('rolls back the evaluation when a later statement violates a constraint', async () => {
      const page = await createPage(ds);

      await expectPgError(
        () =>
          ds.transaction(async (manager) => {
            const evaluations = manager.getRepository(Evaluation);
            await evaluations.save(
              evaluations.create({ pageId: page.id, evaluationDate: new Date() }),
            );
            await manager.getRepository(EvaluationArtifact).insert({
              evaluationId: 999_999,
              artifactType: 'html',
              storageKey: 'tx/html.gz',
              fileSize: 1,
              mimeType: 'text/html',
            });
          }),
        PgErrorCode.FOREIGN_KEY_VIOLATION,
      );

      await expect(ds.getRepository(Evaluation).count()).resolves.toBe(0);
    });

    it('rolls back everything when application code throws mid-transaction', async () => {
      const page = await createPage(ds);

      await expect(
        ds.transaction(async (manager) => {
          const evaluations = manager.getRepository(Evaluation);
          const evaluation = await evaluations.save(
            evaluations.create({ pageId: page.id, evaluationDate: new Date() }),
          );
          await manager.getRepository(EvaluationArtifact).insert({
            evaluationId: evaluation.id,
            artifactType: 'html',
            storageKey: 'tx/html.gz',
            fileSize: 1,
            mimeType: 'text/html',
          });
          throw new Error('simulated failure');
        }),
      ).rejects.toThrow('simulated failure');

      await expect(ds.getRepository(Evaluation).count()).resolves.toBe(0);
      await expect(ds.getRepository(EvaluationArtifact).count()).resolves.toBe(0);
    });
  });

  describe('EvaluationArtifact', () => {
    it('stores one artifact of each type for the same evaluation', async () => {
      const evaluation = await createEvaluation(ds);
      const types: ArtifactType[] = ['assertions', 'html', 'conformance'];

      for (const artifactType of types) {
        await createArtifact(ds, evaluation.id, {
          artifactType,
          storageKey: `evaluations/${evaluation.id}/${artifactType}`,
        });
      }

      const stored = await ds.getRepository(EvaluationArtifact).find({
        where: { evaluationId: evaluation.id },
        order: { artifactType: 'ASC' },
      });
      expect(stored.map((artifact) => artifact.artifactType)).toEqual([
        'assertions',
        'conformance',
        'html',
      ]);
    });

    it('rejects a second artifact with the same (evaluation, type) pair', async () => {
      const evaluation = await createEvaluation(ds);
      await insertArtifact(ds, evaluation.id, { artifactType: 'html', storageKey: 'a/html.gz' });

      await expectPgError(
        () => insertArtifact(ds, evaluation.id, { artifactType: 'html', storageKey: 'b/html.gz' }),
        PgErrorCode.UNIQUE_VIOLATION,
      );
    });

    it('allows the same artifact type on different evaluations', async () => {
      const first = await createEvaluation(ds);
      const second = await createEvaluation(ds);

      await createArtifact(ds, first.id, { artifactType: 'html', storageKey: 'first/html.gz' });
      await createArtifact(ds, second.id, { artifactType: 'html', storageKey: 'second/html.gz' });

      await expect(ds.getRepository(EvaluationArtifact).count()).resolves.toBe(2);
    });

    it('rejects a storage key already used by another artifact', async () => {
      const first = await createEvaluation(ds);
      const second = await createEvaluation(ds);
      await insertArtifact(ds, first.id, { storageKey: 'shared/key.gz' });

      await expectPgError(
        () => insertArtifact(ds, second.id, { storageKey: 'shared/key.gz' }),
        PgErrorCode.UNIQUE_VIOLATION,
      );
    });

    it('rejects an artifact for an evaluation that does not exist (FK)', async () => {
      await expectPgError(() => insertArtifact(ds, 999_999), PgErrorCode.FOREIGN_KEY_VIOLATION);
    });

    it('rejects an artifact without mime_type (NOT NULL)', async () => {
      const evaluation = await createEvaluation(ds);

      await expectPgError(
        () =>
          ds.getRepository(EvaluationArtifact).insert({
            evaluationId: evaluation.id,
            artifactType: 'html',
            storageKey: 'missing/mime.gz',
            fileSize: 1,
          }),
        PgErrorCode.NOT_NULL_VIOLATION,
      );
    });

    it('stores file sizes above the 32-bit integer range (bigint)', async () => {
      const evaluation = await createEvaluation(ds);
      const fileSize = 5_000_000_000;

      const saved = await createArtifact(ds, evaluation.id, { fileSize });
      const found = await ds
        .getRepository(EvaluationArtifact)
        .findOneByOrFail({ evaluationId: evaluation.id, artifactType: saved.artifactType });

      // node-postgres returns bigint as string at runtime
      expect(Number(found.fileSize)).toBe(fileSize);
    });

    it('accepts a zero-byte file', async () => {
      const evaluation = await createEvaluation(ds);

      const saved = await createArtifact(ds, evaluation.id, { fileSize: 0 });
      const found = await ds
        .getRepository(EvaluationArtifact)
        .findOneByOrFail({ evaluationId: evaluation.id, artifactType: saved.artifactType });

      expect(Number(found.fileSize)).toBe(0);
    });

    it('fills created_at automatically', async () => {
      const evaluation = await createEvaluation(ds);

      const saved = await createArtifact(ds, evaluation.id);

      expect(saved.createdAt).toBeInstanceOf(Date);
    });

    it('allows a NULL etag', async () => {
      const evaluation = await createEvaluation(ds);
      await ds.query(
        `INSERT INTO evaluation_artifacts (evaluation_id, artifact_type, storage_key, file_size, mime_type)
         VALUES ($1, 'html', 'raw/html.gz', 10, 'text/html')`,
        [evaluation.id],
      );

      const found = await ds
        .getRepository(EvaluationArtifact)
        .findOneByOrFail({ evaluationId: evaluation.id, artifactType: 'html' });

      expect(found.ETag).toBeNull();
    });

    it('loads the owning evaluation through the relation', async () => {
      const evaluation = await createEvaluation(ds, { pageTitle: 'Owner' });
      await createArtifact(ds, evaluation.id, { artifactType: 'conformance' });

      const found = await ds.getRepository(EvaluationArtifact).findOneOrFail({
        where: { evaluationId: evaluation.id, artifactType: 'conformance' },
        relations: { evaluation: true },
      });

      expect(found.evaluation.pageTitle).toBe('Owner');
    });

    it('is removed together with its evaluation, leaving other artifacts intact', async () => {
      const removed = await createEvaluation(ds);
      const kept = await createEvaluation(ds);
      await createArtifact(ds, removed.id);
      await createArtifact(ds, kept.id);

      await ds.getRepository(Evaluation).delete(removed.id);

      const remaining = await ds.getRepository(EvaluationArtifact).find();
      expect(remaining).toHaveLength(1);
      expect(remaining[0].evaluationId).toBe(kept.id);
    });

    it('lets exactly one of several concurrent inserts for the same (evaluation, type) succeed', async () => {
      const evaluation = await createEvaluation(ds);

      const results = await Promise.allSettled(
        Array.from({ length: 5 }, (_, index) =>
          insertArtifact(ds, evaluation.id, {
            artifactType: 'html',
            storageKey: `concurrent/${index}.gz`,
          }),
        ),
      );

      const fulfilled = results.filter((result) => result.status === 'fulfilled');
      const rejected = results.filter(
        (result): result is PromiseRejectedResult => result.status === 'rejected',
      );

      expect(fulfilled).toHaveLength(1);
      expect(rejected).toHaveLength(4);
      for (const failure of rejected) {
        expect(failure.reason).toBeInstanceOf(QueryFailedError);
        expect(pgErrorCodeOf(failure.reason)).toBe(PgErrorCode.UNIQUE_VIOLATION);
      }
      await expect(ds.getRepository(EvaluationArtifact).count()).resolves.toBe(1);
    });
  });

  describe('EvaluationContext', () => {
    it('links an evaluation to a context and loads both sides', async () => {
      const evaluation = await createEvaluation(ds, { pageTitle: 'Linked' });
      const context = await createContext(ds, { code: 'PUBLIC', name: 'Public' });

      await linkEvaluationToContext(ds, evaluation.id, context.id);

      const link = await ds.getRepository(EvaluationContext).findOneOrFail({
        where: { evaluationId: evaluation.id, contextId: context.id },
        relations: { evaluation: true, context: true },
      });
      expect(link.evaluation.pageTitle).toBe('Linked');
      expect(link.context.code).toBe('PUBLIC');
    });

    it('rejects a duplicated (context, evaluation) link', async () => {
      const evaluation = await createEvaluation(ds);
      const context = await createContext(ds);
      await ds.getRepository(EvaluationContext).insert({
        evaluationId: evaluation.id,
        contextId: context.id,
      });

      await expectPgError(
        () =>
          ds.getRepository(EvaluationContext).insert({
            evaluationId: evaluation.id,
            contextId: context.id,
          }),
        PgErrorCode.UNIQUE_VIOLATION,
      );
    });

    it('supports many contexts per evaluation and many evaluations per context', async () => {
      const [firstEvaluation, secondEvaluation] = await Promise.all([
        createEvaluation(ds),
        createEvaluation(ds),
      ]);
      const [firstContext, secondContext] = await Promise.all([
        createContext(ds),
        createContext(ds),
      ]);

      await linkEvaluationToContext(ds, firstEvaluation.id, firstContext.id);
      await linkEvaluationToContext(ds, firstEvaluation.id, secondContext.id);
      await linkEvaluationToContext(ds, secondEvaluation.id, firstContext.id);

      const repository = ds.getRepository(EvaluationContext);
      await expect(repository.countBy({ evaluationId: firstEvaluation.id })).resolves.toBe(2);
      await expect(repository.countBy({ contextId: firstContext.id })).resolves.toBe(2);
    });

    it('rejects a link to an evaluation that does not exist (FK)', async () => {
      const context = await createContext(ds);

      await expectPgError(
        () =>
          ds.getRepository(EvaluationContext).insert({
            evaluationId: 999_999,
            contextId: context.id,
          }),
        PgErrorCode.FOREIGN_KEY_VIOLATION,
      );
    });

    it('rejects a link to a context that does not exist (FK)', async () => {
      const evaluation = await createEvaluation(ds);

      await expectPgError(
        () =>
          ds.getRepository(EvaluationContext).insert({
            evaluationId: evaluation.id,
            contextId: 999_999,
          }),
        PgErrorCode.FOREIGN_KEY_VIOLATION,
      );
    });

    it('removes only the links of a deleted evaluation', async () => {
      const removed = await createEvaluation(ds);
      const kept = await createEvaluation(ds);
      const context = await createContext(ds);
      await linkEvaluationToContext(ds, removed.id, context.id);
      await linkEvaluationToContext(ds, kept.id, context.id);

      await ds.getRepository(Evaluation).delete(removed.id);

      const links = await ds.getRepository(EvaluationContext).find();
      expect(links).toHaveLength(1);
      expect(links[0].evaluationId).toBe(kept.id);
    });

    it('removes the links but keeps the evaluations when a context is deleted', async () => {
      const evaluation = await createEvaluation(ds);
      const context = await createContext(ds);
      await linkEvaluationToContext(ds, evaluation.id, context.id);

      await ds.getRepository(Context).delete(context.id);

      await expect(ds.getRepository(EvaluationContext).count()).resolves.toBe(0);
      await expect(ds.getRepository(Evaluation).existsBy({ id: evaluation.id })).resolves.toBe(
        true,
      );
    });
  });

  describe('Supporting entities', () => {
    it('enforces a unique context code', async () => {
      await createContext(ds, { code: 'DUPLICATED' });

      await expectPgError(
        () => ds.getRepository(Context).insert({ code: 'DUPLICATED' }),
        PgErrorCode.UNIQUE_VIOLATION,
      );
    });

    it('requires a context code', async () => {
      await expectPgError(
        () => ds.getRepository(Context).insert({ name: 'No code' }),
        PgErrorCode.NOT_NULL_VIOLATION,
      );
    });

    it('requires a username on users', async () => {
      await expectPgError(() => ds.getRepository(User).insert({}), PgErrorCode.NOT_NULL_VIOLATION);
    });

    it('limits usernames to 150 characters', async () => {
      await createUser(ds, { username: 'u'.repeat(150) });

      await expectPgError(
        () => ds.getRepository(User).insert({ username: 'u'.repeat(151) }),
        PgErrorCode.STRING_TOO_LONG,
      );
    });

    it('fills page timestamps automatically', async () => {
      const page = await createPage(ds);

      expect(page.createdAt).toBeInstanceOf(Date);
      expect(page.updatedAt).toBeInstanceOf(Date);
    });
  });
});
